import Foundation

final class XDRBrightnessTests {
    func run() {
        let cached = XDRKeySnapshot(nativeBrightness: 1, allowed: true, sampledAt: 10)
        XCTAssertEqual(cached.action(up: true, gain: 1, active: false, automatic: true, maximum: 3.2, now: 11), .activate(1.05))
        XCTAssertEqual(cached.action(up: true, gain: 1, active: false, automatic: true, maximum: 3.2, now: 13), .system)
        let blocked = XDRKeySnapshot(nativeBrightness: 1, allowed: false, sampledAt: 10)
        XCTAssertEqual(blocked.action(up: true, gain: 1, active: false, automatic: true, maximum: 3.2, now: 10), .system)
        XCTAssertTrue(!XDRBrightnessPolicy.needsOverlay(gain: 1))
        XCTAssertTrue(XDRBrightnessPolicy.needsOverlay(gain: 1.05))
        XCTAssertEqual(XDRBrightnessPolicy.maximumGain(sdrMaximum: 500, peakHDR: 1600, potentialHeadroom: 16), 3.2)
        XCTAssertEqual(XDRBrightnessPolicy.maximumGain(sdrMaximum: 600, peakHDR: 1600, potentialHeadroom: 2), 2)
        XCTAssertEqual(XDRBrightnessPolicy.maximumGain(sdrMaximum: nil, peakHDR: 1600, potentialHeadroom: 16), 1.6)
        XCTAssertEqual(XDRBrightnessPolicy.maximumGain(sdrMaximum: 500, peakHDR: .infinity, potentialHeadroom: 16), 1.6)
        XCTAssertEqual(XDRBrightnessPolicy.clamp(10, maximum: 3.2), 3.2)
        XCTAssertEqual(XDRBrightnessPolicy.keyGain(up: true, gain: 3.2, nativeBrightness: 1, maximum: 3.2), 3.2)
        XCTAssertEqual(XDRBrightnessPolicy.estimatedNits(sdrMaximum: 500, linearBrightness: 1, gain: 3.2, headroom: 3.2), 1600)
        XCTAssertEqual(XDRBrightnessPolicy.estimatedNits(sdrMaximum: 500, linearBrightness: 1, gain: 3.2, headroom: 2), 1000)
        XCTAssertEqual(XDRBrightnessPolicy.estimatedNits(sdrMaximum: 500, linearBrightness: 1, gain: 1.6, headroom: 1.2), 600)
        XCTAssertEqual(XDRBrightnessPolicy.estimatedNits(sdrMaximum: 500, linearBrightness: 0.5, gain: 1.2, headroom: 3.2), 300)
        XCTAssertNil(XDRBrightnessPolicy.estimatedNits(sdrMaximum: nil, linearBrightness: 1, gain: 1.6, headroom: 2))
        XCTAssertNil(XDRBrightnessPolicy.estimatedNits(sdrMaximum: 500, linearBrightness: .nan, gain: 1.6, headroom: 2))
        XCTAssertNil(XDRBrightnessPolicy.estimatedNits(sdrMaximum: 500, linearBrightness: 1, gain: 1.6, headroom: .nan))
        XCTAssertNil(XDRBrightnessPolicy.estimatedNits(sdrMaximum: .infinity, linearBrightness: 1, gain: 1.6, headroom: 2))
        XCTAssertNil(XDRBrightnessPolicy.estimatedNits(sdrMaximum: 500, linearBrightness: -0.1, gain: 1.6, headroom: 2))
        XCTAssertEqual(XDRBrightnessPolicy.keyAction(up: true, gain: 1, active: false, automatic: true, nativeBrightness: 1), .activate(1.05))
        XCTAssertEqual(XDRBrightnessPolicy.keyAction(up: true, gain: 1, active: false, automatic: false, nativeBrightness: 1), .system)
        XCTAssertEqual(XDRBrightnessPolicy.keyAction(up: true, gain: 1, active: false, automatic: true, nativeBrightness: 0.9), .system)
        XCTAssertEqual(XDRBrightnessPolicy.keyAction(up: false, gain: 1, active: false, automatic: true, nativeBrightness: 1), .system)
        XCTAssertEqual(XDRBrightnessPolicy.keyAction(up: true, gain: 1.1, active: true, automatic: false, nativeBrightness: 1), .adjust(1.15))
        var sequence = XDRBrightnessKeySequence()
        XCTAssertTrue(sequence.consumeDown(code: 3, adjusted: true, repeating: false))
        XCTAssertTrue(sequence.consumeDown(code: 3, adjusted: false, repeating: true))
        XCTAssertTrue(sequence.consumeUp(code: 3))
        // 原生按下已送出：XDR 可接管後續重複事件，但放開仍須送回 macOS。
        XCTAssertTrue(!sequence.consumeDown(code: 2, adjusted: false, repeating: false))
        XCTAssertTrue(sequence.shouldAdjustDown(code: 2, repeating: true))
        XCTAssertTrue(sequence.consumeDown(code: 2, adjusted: true, repeating: true))
        XCTAssertTrue(!sequence.consumeUp(code: 2))
        // 掛上監聽時已在重複的按鍵，持續交由 macOS 處理到放開。
        XCTAssertTrue(!sequence.shouldAdjustDown(code: 2, repeating: true))
        XCTAssertTrue(!sequence.consumeDown(code: 2, adjusted: false, repeating: true))
        XCTAssertTrue(!sequence.shouldAdjustDown(code: 2, repeating: true))
        XCTAssertTrue(!sequence.consumeUp(code: 2))
        XCTAssertTrue(sequence.shouldAdjustDown(code: 2, repeating: false))
        XCTAssertEqual(XDRBrightnessPolicy.clamp(.nan), 1)
        XCTAssertEqual(XDRBrightnessPolicy.clamp(10), 1.6)
        XCTAssertEqual(XDRBrightnessPolicy.clamp(-1), 1)
        XCTAssertTrue(XDRBrightnessPolicy.blockReason(supported: true, lowPower: false, hot: false, locked: true) != nil)
        XCTAssertNil(XDRBrightnessPolicy.blockReason(supported: true, lowPower: false, hot: false))
        XCTAssertTrue(XDRBrightnessPolicy.blockReason(supported: false, lowPower: false, hot: false) != nil)
        XCTAssertTrue(XDRBrightnessPolicy.blockReason(supported: true, lowPower: true, hot: false) != nil)
        XCTAssertTrue(XDRBrightnessPolicy.blockReason(supported: true, lowPower: false, hot: true) != nil)
        XCTAssertNil(XDRBrightnessPolicy.keyGain(up: true, gain: 1, nativeBrightness: 0.5))
        XCTAssertNil(XDRBrightnessPolicy.keyGain(up: false, gain: 1, nativeBrightness: 1))
        XCTAssertEqual(XDRBrightnessPolicy.keyGain(up: true, gain: 1, nativeBrightness: 1), 1.05)
        XCTAssertEqual(XDRBrightnessPolicy.keyGain(up: false, gain: 1.05, nativeBrightness: 1), 1)
        XCTAssertEqual(XDRBrightnessPolicy.keyGain(up: true, gain: 1.6, nativeBrightness: 1), 1.6)
    }
}
