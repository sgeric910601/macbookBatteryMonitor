import Foundation

struct ClipboardHistoryTests {
    /// 新的在最前面；重複的內容移到最前面、不重複記；超過上限丟掉最舊的
    func testOrderDedupeAndLimit() {
        var history = ClipboardHistory()
        history.add("第一筆")
        history.add("第二筆")
        history.add("第一筆")
        XCTAssertEqual(history.items, ["第一筆", "第二筆"])
        for i in 0..<40 { history.add("項目 \(i)") }
        XCTAssertEqual(history.items.count, ClipboardHistory.limit)
        XCTAssertEqual(history.items.first, "項目 39")
    }

    /// 空白的不記；太長的截斷
    func testSkipsBlankAndTrimsLong() {
        var history = ClipboardHistory()
        history.add("   \n")
        XCTAssertEqual(history.items, [])
        history.add(String(repeating: "字", count: ClipboardHistory.maxLength + 50))
        XCTAssertEqual(history.items.first?.count, ClipboardHistory.maxLength)
    }

    /// 密碼工具標成機密、暫時或自動產生的內容不記
    func testSkipsConcealedContent() {
        XCTAssertTrue(ClipboardHistory.shouldRecord(types: ["public.utf8-plain-text"]))
        XCTAssertTrue(!ClipboardHistory.shouldRecord(types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]))
        XCTAssertTrue(!ClipboardHistory.shouldRecord(types: ["org.nspasteboard.TransientType", "public.utf8-plain-text"]))
        XCTAssertTrue(!ClipboardHistory.shouldRecord(types: ["org.nspasteboard.AutoGeneratedType"]))
    }

    /// 選單上顯示的預覽：一行、去掉頭尾空白、太長的加刪節號
    func testPreview() {
        XCTAssertEqual(ClipboardHistory.preview("  第一行\n第二行  "), "第一行 第二行")
        XCTAssertEqual(ClipboardHistory.preview(String(repeating: "a", count: 80)), String(repeating: "a", count: 48) + "…")
    }
}
